/** A real route from a UAE airport: the other airport, the aircraft class usually flown, and its flight numbers. */
export interface Route {
  other: string;
  cls: TypeKey;
  /** flights leaving the UAE airport, one per daily frequency */
  out: string[];
  /** the flights coming back, in the same order */
  back: string[];
}

type RouteRow = [other: string, cls: TypeKey, out: string, back: string];
const routes = (rows: RouteRow[]): Route[] => rows.map(([other, cls, out, back]) => ({ other, cls, out: out.split(" "), back: back.split(" ") }));

